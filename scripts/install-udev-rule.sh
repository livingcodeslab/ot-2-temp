#!/usr/bin/env bash
# Grant the current user access to the Opentrons Temperature Module without
# needing sudo every time.  Run this ONCE:   sudo ./scripts/install-udev-rule.sh
#
# It installs two rules:
#   99-opentrons-tempdeck.rules      stable symlink + dialout group + uaccess ACL
#   99-opentrons-tempdeck-acl.rules  explicit ACL for THIS user (works over SSH)
#
# The uaccess ACL only applies to users on a local seat session, so it does
# nothing for an SSH login.  The explicit setfacl rule covers that case.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RULE="99-opentrons-tempdeck.rules"
ACL_RULE="99-opentrons-tempdeck-acl.rules"
RULES_DIR="/etc/udev/rules.d"

if [[ $EUID -ne 0 ]]; then
    echo "This script needs root. Re-run with:  sudo $0" >&2
    exit 1
fi

# The human who invoked sudo (falls back to $USER when run as real root).
TARGET_USER="${SUDO_USER:-${USER}}"
if [[ -z "${TARGET_USER}" || "${TARGET_USER}" == "root" ]]; then
    echo "Could not determine the non-root user to grant access to." >&2
    echo "Run as:  sudo ./scripts/install-udev-rule.sh   (not from a root shell)" >&2
    exit 1
fi

if ! command -v setfacl >/dev/null 2>&1; then
    echo "setfacl not found; install the 'acl' package: sudo apt install acl" >&2
    exit 1
fi

install -m 0644 "${HERE}/${RULE}" "${RULES_DIR}/${RULE}"
echo "Installed ${RULES_DIR}/${RULE}"

cat > "${RULES_DIR}/${ACL_RULE}" <<EOF
# Generated by ot-2-temp/scripts/install-udev-rule.sh -- grants ${TARGET_USER}
# read/write access to the Opentrons Temperature Module.  Explicit ACL is used
# because TAG+="uaccess" only covers users with a local (seat) session.
SUBSYSTEM=="tty", ATTRS{idVendor}=="04d8", ATTRS{idProduct}=="ee93", RUN+="/usr/bin/setfacl -m u:${TARGET_USER}:rw /dev/%k"
EOF
chmod 0644 "${RULES_DIR}/${ACL_RULE}"
echo "Installed ${RULES_DIR}/${ACL_RULE} (ACL for user ${TARGET_USER})"

udevadm control --reload-rules
udevadm trigger --subsystem-match=tty --action=change
udevadm settle

# Apply the ACL right now as well, so no replug is needed.
for dev in /dev/ttyACM*; do
    [[ -e "${dev}" ]] || continue
    if udevadm info -q property -n "${dev}" | grep -q '^ID_MODEL_ID=ee93$'; then
        setfacl -m "u:${TARGET_USER}:rw" "${dev}"
    fi
done

echo
echo "Current access:"
getfacl -p /dev/ttyACM0 2>/dev/null || true
ls -l /dev/opentrons_tempdeck /dev/ttyACM* 2>/dev/null || true
echo
if [[ -n "${SSH_CONNECTION:-}" ]]; then
    echo "NOTE: you are on an SSH session, so the uaccess ACL does not apply --"
    echo "the explicit ACL above is what gives ${TARGET_USER} access. That should"
    echo "be enough; if not, replug the module or log out and back in."
else
    echo "If access still fails, unplug and replug the module, or log out/in."
fi
